/** Random bench of n distinct figurines (nothing is preselected). */
export function randomBench(n = 5, exclude: string[] = []): string[] {
  const ids = Object.keys(PIECES).filter(id => !exclude.includes(id));
  for (let i = ids.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [ids[i], ids[j]] = [ids[j], ids[i]];
  }
  return ids.slice(0, n);
}

